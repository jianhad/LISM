create table sys_organization (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null default 1,
    code varchar(64) not null unique,
    name varchar(200) not null,
    status varchar(32) not null default 'ENABLED',
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    version integer not null default 0,
    deleted boolean not null default false
);

create table sys_department (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null default 1,
    organization_id bigint not null references sys_organization(id),
    parent_id bigint references sys_department(id),
    code varchar(64) not null,
    name varchar(200) not null,
    path varchar(1000) not null,
    status varchar(32) not null default 'ENABLED',
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    version integer not null default 0,
    deleted boolean not null default false,
    unique (tenant_id, code)
);

create table sys_user (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null default 1,
    username varchar(64) not null,
    password_hash varchar(200) not null,
    display_name varchar(100) not null,
    dept_id bigint references sys_department(id),
    status varchar(32) not null default 'ENABLED',
    password_changed_at timestamp,
    last_login_at timestamp,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    version integer not null default 0,
    deleted boolean not null default false,
    unique (tenant_id, username)
);

create table sys_role (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null default 1,
    code varchar(100) not null,
    name varchar(100) not null,
    status varchar(32) not null default 'ENABLED',
    built_in boolean not null default false,
    created_at timestamp not null default current_timestamp,
    updated_at timestamp not null default current_timestamp,
    version integer not null default 0,
    deleted boolean not null default false,
    unique (tenant_id, code)
);

create table sys_permission (
    id bigint generated by default as identity primary key,
    code varchar(150) not null unique,
    name varchar(150) not null,
    type varchar(32) not null,
    status varchar(32) not null default 'ENABLED'
);

create table sys_user_role (
    user_id bigint not null references sys_user(id),
    role_id bigint not null references sys_role(id),
    valid_from timestamp,
    valid_to timestamp,
    primary key (user_id, role_id)
);

create table sys_role_permission (
    role_id bigint not null references sys_role(id),
    permission_id bigint not null references sys_permission(id),
    primary key (role_id, permission_id)
);

create table sys_role_data_scope (
    id bigint generated by default as identity primary key,
    role_id bigint not null references sys_role(id),
    scope_type varchar(32) not null,
    dept_id bigint references sys_department(id)
);

create table audit_operation (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null default 1,
    actor_id bigint references sys_user(id),
    action varchar(150) not null,
    object_type varchar(100) not null,
    object_id varchar(100),
    result varchar(32) not null,
    before_summary text,
    after_summary text,
    reason varchar(1000),
    ip varchar(64),
    occurred_at timestamp not null default current_timestamp
);

create index idx_sys_user_dept on sys_user(dept_id);
create index idx_user_role_user on sys_user_role(user_id);
create index idx_audit_actor_time on audit_operation(actor_id, occurred_at desc);
create index idx_audit_object on audit_operation(object_type, object_id);

